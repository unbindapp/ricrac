import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const iconsDir = join(root, "src/components/icons");
const symbolsDir = join(root, "node_modules/@material-symbols/svg-400/rounded");
const map = JSON.parse(readFileSync(join(iconsDir, "symbol-map.json"), "utf8"));
const singlePath =
  /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" width="48" height="48" viewBox="0 -960 960 960"><path d="([^"]+)"\/><\/svg>\s*$/;

function pathData(file) {
  const match = singlePath.exec(readFileSync(file, "utf8"));
  if (!match) throw new Error(`${file} is not a single path on the 0 -960 960 960 viewBox`);
  return match[1];
}

const missing = [...new Set(Object.values(map))].filter(
  (name) => !existsSync(join(symbolsDir, `${name}.svg`)),
);
if (missing.length > 0) {
  console.error(`Not in @material-symbols/svg-400/rounded: ${missing.join(", ")}`);
  process.exit(1);
}

const names = Object.keys(map).sort();
const header = (what) =>
  `// Generated by scripts/generate-symbols.mjs from src/components/icons/symbol-map.json. Do not edit.\n// ${what}\n`;

const paths = names.map((component) => {
  const outline = pathData(join(symbolsDir, `${map[component]}.svg`));
  const fill = pathData(join(symbolsDir, `${map[component]}-fill.svg`));
  const entry = fill === outline ? `["${outline}"]` : `["${outline}", "${fill}"]`;
  return `  ${component}: ${entry},`;
});

const symbolsSource = `${header("Material Symbols Rounded (@material-symbols/svg-400), Apache-2.0.")}import type { TSymbolPaths } from "./symbol-set.ts";

export const symbolPaths: TSymbolPaths = {
${paths.join("\n")}
};
`;

const indexSource = `${header("Every icon the app uses: lucide, or its Material Symbols glyph when the theme asks for it.")}import {
${names.map((name) => `  ${name} as Lucide${name},`).join("\n")}
} from "lucide-react";

import { themedIcon } from "./themed-icon.ts";

export type { LucideIcon, LucideProps } from "lucide-react";

${names.map((name) => `export const ${name} = /* @__PURE__ */ themedIcon(Lucide${name}, "${name}");`).join("\n")}
`;

const symbolsFile = join(iconsDir, "symbols.gen.ts");
const indexFile = join(iconsDir, "index.ts");
writeFileSync(symbolsFile, symbolsSource);
writeFileSync(indexFile, indexSource);
execFileSync(
  join(root, "node_modules/.bin/prettier"),
  ["--write", "--log-level", "warn", indexFile],
  { cwd: root, stdio: "inherit" },
);
console.log(`Wrote ${names.length} icons to src/components/icons/index.ts and symbols.gen.ts`);
