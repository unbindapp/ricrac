import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const symbolsDir = join(root, "node_modules/@material-symbols/svg-400/rounded");
const mapFile = join(root, "src/components/icons/symbol-map.json");
const outFile = join(root, "src/components/icons/symbols.gen.ts");
const singlePath =
  /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" width="48" height="48" viewBox="0 -960 960 960"><path d="([^"]+)"\/><\/svg>\s*$/;

function pathData(file) {
  const match = singlePath.exec(readFileSync(file, "utf8"));
  if (!match) throw new Error(`${file} is not a single path on the 0 -960 960 960 viewBox`);
  return match[1];
}

const map = JSON.parse(readFileSync(mapFile, "utf8"));
const missing = [...new Set(Object.values(map))].filter(
  (name) => !existsSync(join(symbolsDir, `${name}.svg`)),
);
if (missing.length > 0) {
  console.error(`Not in @material-symbols/svg-400/rounded: ${missing.join(", ")}`);
  process.exit(1);
}

const exports = Object.keys(map)
  .sort()
  .map((component) => {
    const name = map[component];
    const outline = pathData(join(symbolsDir, `${name}.svg`));
    const fill = pathData(join(symbolsDir, `${name}-fill.svg`));
    const args = fill === outline ? `"${outline}"` : `"${outline}", "${fill}"`;
    return `export const ${component} = /* @__PURE__ */ symbol("${component}", ${args});`;
  });

const source = `// Generated by scripts/generate-symbols.mjs from src/components/icons/symbol-map.json. Do not edit.
// Material Symbols Rounded (@material-symbols/svg-400), Apache-2.0.
import { createElement, type ReactElement, type SVGProps } from "react";

export type TIconProps = SVGProps<SVGSVGElement> & { filled?: boolean };
export type TIcon = ((props: TIconProps) => ReactElement) & { displayName: string };

function symbol(displayName: string, outline: string, fill = outline): TIcon {
  const Icon = ({ filled, ...props }: TIconProps) =>
    createElement(
      "svg",
      {
        xmlns: "http://www.w3.org/2000/svg",
        viewBox: "0 -960 960 960",
        width: 24,
        height: 24,
        fill: "currentColor",
        "aria-hidden": props["aria-label"] ? undefined : true,
        ...props,
      },
      createElement("path", { d: filled ? fill : outline }),
    );
  return Object.assign(Icon, { displayName });
}

${exports.join("\n")}
`;

writeFileSync(outFile, source);
console.log(`Wrote ${exports.length} symbols to ${outFile.slice(root.length)}`);
