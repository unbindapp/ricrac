package ops

import (
	"fmt"
	"reflect"
	"slices"
	"strconv"
	"strings"
)

// TypeScript is the web client's types: every operation's arguments and result, and an Ops map
// from operation names to both.
func TypeScript() (string, error) {
	g := &tsGen{defs: map[string]string{}}
	var ops strings.Builder
	var args strings.Builder
	for _, o := range All() {
		argsName := pascal(o.Name) + "Args"
		body, err := g.object(o.Schema, "")
		if err != nil {
			return "", fmt.Errorf("%s arguments: %w", o.Name, err)
		}
		fmt.Fprintf(&args, "export type %s = %s\n\n", argsName, body)
		result := "unknown"
		if o.Result != nil {
			if result, err = g.typeOf(o.Result, ""); err != nil {
				return "", fmt.Errorf("%s result: %w", o.Name, err)
			}
		}
		fmt.Fprintf(&ops, "  %s: { args: %s; result: %s }\n", o.Name, argsName, result)
	}
	var out strings.Builder
	out.WriteString("// Generated by `go test ./ops` in apps/server from the operations' schemas. Do not edit.\n\n")
	names := make([]string, 0, len(g.defs))
	for name := range g.defs {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		fmt.Fprintf(&out, "export type %s = %s\n\n", name, g.defs[name])
	}
	out.WriteString(args.String())
	out.WriteString("export interface Ops {\n" + ops.String() + "}\n\nexport type OpName = keyof Ops\n")
	return out.String(), nil
}

type tsGen struct {
	defs map[string]string
}

func pascal(name string) string {
	var out strings.Builder
	for _, part := range strings.Split(name, "_") {
		if part != "" {
			out.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return out.String()
}

func (g *tsGen) typeOf(schema M, indent string) (string, error) {
	if len(schema) == 0 {
		return "unknown", nil
	}
	for _, key := range []string{"anyOf", "oneOf"} {
		if options, ok := schema[key].([]any); ok {
			var parts []string
			for _, option := range options {
				part, err := g.typeOf(option.(M), indent)
				if err != nil {
					return "", err
				}
				parts = append(parts, part)
			}
			return strings.Join(parts, " | "), nil
		}
	}
	if value, ok := schema["const"]; ok {
		return literal(value), nil
	}
	if values, ok := schema["enum"].([]any); ok {
		parts := make([]string, len(values))
		for i, v := range values {
			parts[i] = literal(v)
		}
		return strings.Join(parts, " | "), nil
	}
	var kinds []string
	switch t := schema["type"].(type) {
	case string:
		kinds = []string{t}
	case []any:
		for _, k := range t {
			kinds = append(kinds, k.(string))
		}
	}
	var parts []string
	for _, kind := range kinds {
		var part string
		switch kind {
		case "string":
			part = "string"
		case "integer", "number":
			part = "number"
		case "boolean":
			part = "boolean"
		case "null":
			part = "null"
		case "array":
			items, _ := schema["items"].(M)
			item, err := g.typeOf(items, indent)
			if err != nil {
				return "", err
			}
			if strings.ContainsAny(item, "|&") {
				item = "(" + item + ")"
			}
			part = item + "[]"
		case "object":
			named, err := g.namedObject(schema, indent)
			if err != nil {
				return "", err
			}
			part = named
		}
		parts = append(parts, part)
	}
	if len(parts) == 0 {
		return "unknown", nil
	}
	return strings.Join(parts, " | "), nil
}

func (g *tsGen) namedObject(schema M, indent string) (string, error) {
	title, _ := schema["title"].(string)
	if title == "" {
		return g.object(schema, indent)
	}
	body, err := g.object(schema, "")
	if err != nil {
		return "", err
	}
	if existing, ok := g.defs[title]; ok && existing != body {
		return "", fmt.Errorf("two different shapes are named %s", title)
	}
	g.defs[title] = body
	return title, nil
}

func (g *tsGen) object(schema M, indent string) (string, error) {
	properties, _ := schema["properties"].(M)
	if len(properties) == 0 {
		if extra, ok := schema["additionalProperties"].(M); ok {
			value, err := g.typeOf(extra, indent)
			return "Record<string, " + value + ">", err
		}
		if schema["additionalProperties"] == false {
			return "Record<string, never>", nil
		}
		return "Record<string, unknown>", nil
	}
	required := map[string]bool{}
	list, _ := schema["required"].([]any)
	for _, name := range list {
		required[name.(string)] = true
	}
	names := make([]string, 0, len(properties))
	for name := range properties {
		names = append(names, name)
	}
	slices.Sort(names)
	inner := indent + "  "
	var out strings.Builder
	out.WriteString("{\n")
	for _, name := range names {
		property := properties[name].(M)
		if doc, ok := property["description"].(string); ok && doc != "" {
			fmt.Fprintf(&out, "%s/** %s */\n", inner, strings.ReplaceAll(doc, "*/", "* /"))
		}
		value, err := g.typeOf(property, inner)
		if err != nil {
			return "", fmt.Errorf("%s: %w", name, err)
		}
		optional := "?"
		if required[name] {
			optional = ""
		}
		fmt.Fprintf(&out, "%s%s%s: %s\n", inner, name, optional, value)
	}
	out.WriteString(indent + "}")
	return out.String(), nil
}

func literal(value any) string {
	switch v := value.(type) {
	case nil:
		return "null"
	case string:
		return strconv.Quote(v)
	}
	return fmt.Sprint(value)
}

// TypeScriptFor is TypeScript types for Go structs outside the operations, like the dashboard's:
// results have every field (pointers may be null), requests leave pointers optional.
func TypeScriptFor(results []any, requests []any) (string, error) {
	g := &tsGen{defs: map[string]string{}}
	for _, value := range results {
		if _, err := g.typeOf(schemas{result: true}.of(reflect.TypeOf(value)), ""); err != nil {
			return "", err
		}
	}
	for _, value := range requests {
		t := reflect.TypeOf(value)
		schema := schemas{}.of(t)
		schema["title"] = t.Name()
		if _, err := g.typeOf(schema, ""); err != nil {
			return "", err
		}
	}
	var out strings.Builder
	out.WriteString("// Generated by `go test ./server` in apps/server. Do not edit.\n\n")
	names := make([]string, 0, len(g.defs))
	for name := range g.defs {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		fmt.Fprintf(&out, "export type %s = %s\n\n", name, g.defs[name])
	}
	return strings.TrimSuffix(out.String(), "\n"), nil
}
